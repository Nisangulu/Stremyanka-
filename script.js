// Функция генерации галереи
function renderGallery(model) {
  const container = document.getElementById('gallery-container');
  container.innerHTML = '';

  if (!modelInfo[model]) {
    console.error(`Модель "${model}" не найдена в modelInfo.`);
    return;
  }

  modelInfo[model].forEach((item, index) => {
    const imgA = `../images/${model}-${index + 1}a.jpg`;
    const imgB = `../images/${model}-${index + 1}b.jpg`;

    const div = document.createElement('div');
    div.className = 'gallery-item';
    div.innerHTML = `
      <h2>${item.name}</h2>
      <img src="${imgA}" alt="${item.name}">
      <ul>
        ${item.characteristics.map(c => `<li>${c}</li>`).join('')}
      </ul>
      <p class="price">${item.price}</p>
    `;

    div.onclick = () => openGallery([imgA, imgB]);
    container.appendChild(div);
  });
}


// Открытие лайтбокса
function openGallery(images) {
  galleryImages = images;
  currentIndex = 0;
  const lightbox = document.getElementById('lightbox');
  const lightboxImg = document.getElementById('lightbox-img');

  if (!lightbox || !lightboxImg) {
    console.error('Лайтбокс элементы не найдены.');
    return;
  }

  lightbox.style.display = 'flex';
  lightboxImg.src = galleryImages[currentIndex];
}

// Закрытие лайтбокса
function closeGallery() {
  const lightbox = document.getElementById('lightbox');
  if (lightbox) lightbox.style.display = 'none';
}

// Следующее фото
function nextImage(event) {
  event.stopPropagation();
  currentIndex = (currentIndex + 1) % galleryImages.length;
  document.getElementById('lightbox-img').src = galleryImages[currentIndex];
}

// Предыдущее фото
function prevImage(event) {
  event.stopPropagation();
  currentIndex = (currentIndex - 1 + galleryImages.length) % galleryImages.length;
  document.getElementById('lightbox-img').src = galleryImages[currentIndex];
}
